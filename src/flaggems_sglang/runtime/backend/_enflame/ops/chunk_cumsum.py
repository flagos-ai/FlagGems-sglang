"""Enflame scan: triangular-dot prefix sum with a masked 2D fallback.

`tl.cumsum` lowers to deslice/slice round-trips on GCU and costs ~99% of
the runtime (3.5ms vs a 0.033ms load/store floor on the core shapes), so the
fast path replaces the in-chunk scan with `tl.dot(tri, da)` where `tri` is a
loop-invariant inclusive lower-triangular matrix (perf_playbook precedent:
vllm main_chunk_local_cumsum_scalar_kernel). num_warps must stay 4 and every
h-block must be full-width: fp32 `tl.dot` silently mis-compiles for
num_warps < 4 and for partial-N tiles with BLOCK_T >= 32 (see
compiler_issues/sglang_chunk_cumsum_dot_silent_miscompile.md), so odd head
counts and non-unit h-strides fall back to the portable tl.cumsum kernel.

When every chunk is provably full (seqlen % chunk_size == 0 and the chunk
is a multiple of BLOCK_T), the tail masks are statically all-true; a
FULL_CHUNKS constexpr arm then drops them entirely. Masked loads/stores
around the dot tile are a measured hot-path tax (2026-11-12 ablation:
106.6 -> 62.1us on (32,4,256,64), 61.9 -> 56.0us on (8,16,256,32)), so the
unmasked arm is dispatched whenever it is provably exact; partial chunks
keep the masked kernel.
"""


import torch
import triton
import triton.language as tl

__all__ = ["chunk_cumsum"]


@triton.jit
def _softplus_fp32(x):
    # max(x, 0) + log(1 + exp(-abs(x))) is stable at both tails.
    return tl.maximum(x, 0.0) + tl.log(1.0 + tl.exp(-tl.abs(x)))


@triton.jit
def _chunk_cumsum_kernel(
    dt_ptr,
    a_ptr,
    bias_ptr,
    dt_out_ptr,
    da_cumsum_ptr,
    seqlen,
    nheads,
    nchunks,
    chunk_size,
    stride_dt_b,
    stride_dt_s,
    stride_dt_h,
    stride_a_h,
    stride_bias_h,
    HAS_BIAS: tl.constexpr,
    DT_SOFTPLUS: tl.constexpr,
    BLOCK_H: tl.constexpr,
    BLOCK_K: tl.constexpr,
):
    pid_b = tl.program_id(0)
    pid_c = tl.program_id(1)
    pid_h = tl.program_id(2)

    offs_h = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)
    offs_k = tl.arange(0, BLOCK_K)
    offs_s = pid_c * chunk_size + offs_k

    valid_h = offs_h < nheads
    valid_k = offs_k < chunk_size
    valid_s = offs_s < seqlen
    load_mask = valid_h[:, None] & valid_k[None, :] & valid_s[None, :]

    dt_offsets = (
        pid_b * stride_dt_b
        + offs_s[None, :] * stride_dt_s
        + offs_h[:, None] * stride_dt_h
    )
    dt = tl.load(dt_ptr + dt_offsets, mask=load_mask, other=0.0).to(tl.float32)

    if HAS_BIAS:
        bias = tl.load(
            bias_ptr + offs_h * stride_bias_h,
            mask=valid_h,
            other=0.0,
        ).to(tl.float32)
        dt += bias[:, None]

    if DT_SOFTPLUS:
        # Match torch.nn.functional.softplus's default threshold.
        dt = tl.where(dt <= 20.0, _softplus_fp32(dt), dt)

    dt = tl.maximum(dt, 0.0)
    # Bias/softplus can turn a masked zero into a nonzero; mask again.
    dt = tl.where(load_mask, dt, 0.0)

    out_offsets = (
        (pid_b * nheads + offs_h[:, None]) * nchunks + pid_c
    ) * chunk_size + offs_k[None, :]
    store_mask = valid_h[:, None] & valid_k[None, :]
    tl.store(dt_out_ptr + out_offsets, dt, mask=store_mask)

    a = tl.load(
        a_ptr + offs_h * stride_a_h,
        mask=valid_h,
        other=0.0,
    ).to(tl.float32)
    da = dt * a[:, None]
    da_cumsum = tl.cumsum(da, axis=1)
    tl.store(da_cumsum_ptr + out_offsets, da_cumsum, mask=store_mask)


@triton.jit
def _chunk_cumsum_dot_kernel(
    dt_ptr,
    a_ptr,
    bias_ptr,
    dt_out_ptr,
    da_cumsum_ptr,
    seqlen,
    nheads,
    nchunks,
    chunk_size,
    stride_dt_b,
    stride_dt_s,
    stride_dt_h,
    stride_a_h,
    stride_bias_h,
    HAS_BIAS: tl.constexpr,
    DT_SOFTPLUS: tl.constexpr,
    BLOCK_H: tl.constexpr,
    BLOCK_T: tl.constexpr,
    NUM_SUB: tl.constexpr,
    FULL_CHUNKS: tl.constexpr,
):
    # One program covers a full-width [BLOCK_H] head block of one chunk; the
    # chunk is scanned in NUM_SUB sub-tiles of BLOCK_T steps each, chaining a
    # per-column carry between sub-tiles. tri[i, j] = 1.0 iff j <= i, so
    # dot(tri, da) is the inclusive prefix sum along the chunk axis.
    # FULL_CHUNKS drops the tail masks when every chunk and every sub-tile is
    # provably in-bounds: masked loads/stores around the dot tile are a
    # measured hot-path tax (2026-11-12 ablation, BH=64 core shape: 42%).
    pid_bc = tl.program_id(0)
    pid_h = tl.program_id(1)
    pid_c = pid_bc % nchunks
    pid_b = pid_bc // nchunks

    offs_t = tl.arange(0, BLOCK_T)
    offs_h = pid_h * BLOCK_H + tl.arange(0, BLOCK_H)

    tri = tl.where(offs_t[None, :] <= offs_t[:, None], 1.0, 0.0)
    a = tl.load(a_ptr + offs_h * stride_a_h).to(tl.float32)
    if HAS_BIAS:
        bias = tl.load(bias_ptr + offs_h * stride_bias_h).to(tl.float32)

    carry = tl.zeros([BLOCK_H], dtype=tl.float32)
    for sub in tl.static_range(NUM_SUB):
        offs_ts = sub * BLOCK_T + offs_t
        offs_s = pid_c * chunk_size + offs_ts

        dt_offsets = (
            pid_b * stride_dt_b
            + offs_s[:, None] * stride_dt_s
            + offs_h[None, :] * stride_dt_h
        )
        if FULL_CHUNKS:
            dt = tl.load(dt_ptr + dt_offsets).to(tl.float32)
        else:
            valid_t = offs_ts < chunk_size
            valid_s = offs_s < seqlen
            load_mask = valid_t[:, None] & valid_s[:, None]
            dt = tl.load(dt_ptr + dt_offsets, mask=load_mask, other=0.0).to(
                tl.float32
            )
        if HAS_BIAS:
            dt += bias[None, :]
        if DT_SOFTPLUS:
            dt = tl.where(dt <= 20.0, _softplus_fp32(dt), dt)
        dt = tl.maximum(dt, 0.0)
        if not FULL_CHUNKS:
            # Bias/softplus can turn a masked zero into a nonzero; mask again.
            dt = tl.where(load_mask, dt, 0.0)

        out_base = (
            (pid_b * nheads + offs_h[None, :]) * nchunks + pid_c
        ) * chunk_size + offs_ts[:, None]
        if FULL_CHUNKS:
            tl.store(dt_out_ptr + out_base, dt)

            da = dt * a[None, :]
            da_cumsum = tl.dot(tri, da, allow_tf32=False)
            da_cumsum += carry[None, :]
            tl.store(da_cumsum_ptr + out_base, da_cumsum)
        else:
            tl.store(dt_out_ptr + out_base, dt, mask=load_mask)

            da = dt * a[None, :]
            da_cumsum = tl.dot(tri, da, allow_tf32=False)
            da_cumsum += carry[None, :]
            tl.store(da_cumsum_ptr + out_base, da_cumsum, mask=load_mask)
        carry += tl.sum(da, axis=0)


def _launch_config(block_k, nheads, work):
    """Select shape/dtype tuning for the fallback implementation."""
    min_block_h = max(1, 512 // block_k)
    max_block_h = max(1, 32768 // block_k)
    block_h = max(
        min_block_h, min(triton.next_power_of_2(nheads), max_block_h)
    )
    return (block_h, 2 if work <= 1024 else 1)


def _dot_block_h(nheads):
    """Largest full-width head block for the dot path, or 0 if none.

    Partial-N dot tiles mis-compile (see module docstring), so the block must
    divide nheads exactly; the h-stride of dt must be unit as well.
    """
    for block_h in (64, 32, 16):
        if nheads % block_h == 0:
            return block_h
    return 0


